/// 五层同心球壳 —— 语义节点将来待的地方。
///
/// `ADR-0006` 决策表的「布局」写的是**同心球壳，半径按对数等比**：同一层上的
/// 节点到球心等距，层与层之间按固定倍数放大。相机固定在球心、只旋转不平移，
/// 所以**壳本身在画面上是看不见的**（看不见一个与自己同心的球面），能看到的
/// 只有落在壳上的点 —— 而现在还没有节点。
///
/// **2026-10-31 删去经纬网格**。段 2 曾给每层球面画 12 条经线 + 5 条纬线，
/// 目的是「一眼数出几层、半径比例对不对」。实测这个目的达不到：相机在球心，
/// 五层球面上的同经纬度点**投影后完全重合**，屏幕上是同一套线叠五次。
/// 后果有两个 ——
///
/// 1. 亮度叠成五倍（每层 alpha 0.10，五次约 0.41），比星座连线显眼得多，
///    fov 拉大、视角靠近球壳极点时经线在一处汇聚，整屏像一张蛛网（见
///    2026-10-31 的实机截图）。
/// 2. 「数出几层」从来没被真正验过：球心视角下数不出环，段 3 当时读的是
///    面板上那行字。
///
/// 所以网格整体移除，**层数与半径比例这些结构定义保留**。
///
/// **2026-11-01 半径收编进常量表**（`B17b` 笔 2）。原先这里有一套
/// `kInnermostShellRadius` / `kShellRadiusRatio` / `kShellCount`，与
/// `core/constants.dart` 的 `C-124`–`C-126` 同值并存 —— 那是笔 1 留下的临时
/// 状态（`ADR-0006` 修订十二明写「笔 2 收编时删旧的」）。现在只剩常量表一份，
/// 半径计算统一走 `core/universe/placement.dart` 的 `shellRadiusOf()`，本文件
/// 不再重复那条公式。
///
/// **层数按三轴的真实深度取最大值，不为视觉对称造层**。学科与专业只有 4 层
/// （根 / 门类或大类 / 一级或中类 / 学位类别或小类或细类），角色轴 5 层；
/// 若为了「三轴一样深」凑成 7 层，等于给编目里不存在的层级造壳 ——
/// 那是 `MEMORY-rules` §三 明确禁止的做法（「深度是编目的函数」）。
/// 浅轴用不满 5 层，最外层留空。
library;

import '../../../core/constants.dart';

/// 三轴各自的层级深度。键用轴名，与 `enums.dart` 的 `Axis` 取值一致。
///
/// `level_slot` 的 12 个合法对是「学科 3 / 专业 4 / 角色 5」，加上轴根即
/// 4 / 5 / 6；这里记的是**不含虚拟根 `知识`** 的层数 —— 虚拟根不在球壳上，
/// 它没有位置（与面包屑第 1 段同判据）。
const Map<String, int> kAxisDepth = <String, int>{
  'discipline': 4,
  'major': 4,
  'occupation': 5,
};

/// 某条轴实际用得上几层。取不到轴名时按最深轴给 —— 未知轴不缩水。
int shellDepthForAxis(String axis) => kAxisDepth[axis] ?? universeShellCount;
